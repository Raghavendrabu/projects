// frontend/src/pages/CourseDetail.jsx
import React, { useState, useEffect } from 'react';
import { useParams, Link } from 'react-router-dom';
import { ArrowLeft, Book, Target, CheckCircle, FileText, BarChart, BookOpen, Download, Layout, Clock, Award } from 'lucide-react';
import { getCourseDetails } from '../api';
import jsPDF from 'jspdf';
import 'jspdf-autotable';

function CourseDetail() {
  const { id } = useParams();
  const [course, setCourse] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    const fetchDetail = async () => {
      try {
        setLoading(true);
        const data = await getCourseDetails(id);
        setCourse(data);
      } catch (err) {
        setError('Failed to fetch course details.');
      } finally {
        setLoading(false);
      }
    };
    fetchDetail();
  }, [id]);

  const generatePDF = () => {
    if (!course) return;
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    let yPos = 25;

    // Helper for page borders and header
    const addPageDecoration = (doc, pageNum) => {
      doc.setDrawColor(44, 62, 80);
      doc.setLineWidth(0.5);
      doc.rect(10, 10, pageWidth - 20, doc.internal.pageSize.getHeight() - 20); // Border
      
      doc.setFontSize(8);
      doc.setFont("helvetica", "italic");
      doc.text(`Generated by CourseHub - Page ${pageNum}`, pageWidth - 50, doc.internal.pageSize.getHeight() - 15);
    };

    addPageDecoration(doc, 1);

    // Main Header
    doc.setFillColor(44, 62, 80);
    doc.rect(10, 10, pageWidth - 20, 20, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(18);
    doc.setFont("helvetica", "bold");
    doc.text("OFFICIAL COURSE SYLLABUS", pageWidth / 2, 23, { align: "center" });
    
    doc.setTextColor(0, 0, 0);
    yPos = 45;

    // Course Info Block
    doc.setFontSize(14);
    doc.text(course.courseTitle.toUpperCase(), 15, yPos);
    yPos += 8;
    doc.setFontSize(11);
    doc.setFont("helvetica", "normal");
    doc.text(`Course Code: ${course.courseCode}`, 15, yPos);
    doc.text(`Credits: ${course.credits}`, 100, yPos);
    doc.text(`LTP: ${course.ltp}`, 150, yPos);
    yPos += 12;

    doc.setDrawColor(200, 200, 200);
    doc.line(15, yPos, pageWidth - 15, yPos);
    yPos += 10;

    // Section 1: Aims
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("1. COURSE AIMS & SUMMARY", 15, yPos);
    yPos += 7;
    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    const aimsLines = doc.splitTextToSize(course.aims, pageWidth - 30);
    doc.text(aimsLines, 15, yPos);
    yPos += aimsLines.length * 5 + 10;

    // Section 2: Objectives
    if (yPos > 240) { doc.addPage(); yPos = 25; addPageDecoration(doc, doc.internal.getNumberOfPages()); }
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("2. COURSE OBJECTIVES", 15, yPos);
    yPos += 7;
    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    course.objectives.forEach((obj, idx) => {
      if (yPos > 270) { doc.addPage(); yPos = 25; addPageDecoration(doc, doc.internal.getNumberOfPages()); }
      const objLines = doc.splitTextToSize(obj, pageWidth - 35);
      doc.text(objLines, 15, yPos);
      yPos += objLines.length * 5;
    });
    yPos += 10;

    // Section 3: Outcomes
    if (yPos > 240) { doc.addPage(); yPos = 25; addPageDecoration(doc, doc.internal.getNumberOfPages()); }
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("3. COURSE OUTCOMES (COs)", 15, yPos);
    const outcomesData = course.outcomes.map(co => [co.code, co.description]);
    doc.autoTable({
      startY: yPos + 5,
      margin: { left: 15, right: 15 },
      head: [['Code', 'Outcome Description']],
      body: outcomesData,
      theme: 'grid',
      headStyles: { fillColor: [44, 62, 80] },
      styles: { fontSize: 9 }
    });
    yPos = doc.lastAutoTable.finalY + 15;

    // Section 4: Syllabus
    if (yPos > 240) { doc.addPage(); yPos = 25; addPageDecoration(doc, doc.internal.getNumberOfPages()); }
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("4. COURSE CONTENT (SYLLABUS)", 15, yPos);
    yPos += 5;

    course.syllabusUnits.forEach(unit => {
      if (yPos > 250) { doc.addPage(); yPos = 25; addPageDecoration(doc, doc.internal.getNumberOfPages()); }
      doc.setFontSize(11);
      doc.setFont("helvetica", "bold");
      doc.setFillColor(240, 240, 240);
      doc.rect(15, yPos, pageWidth - 30, 7, 'F');
      doc.text(`UNIT ${unit.unitNumber}: ${unit.title}`, 18, yPos + 5);
      yPos += 10;
      
      doc.setFontSize(9);
      doc.setFont("helvetica", "normal");
      const topicText = unit.topics.join(', ');
      const topicLines = doc.splitTextToSize(topicText, pageWidth - 35);
      doc.text(topicLines, 18, yPos);
      yPos += topicLines.length * 5 + 5;
    });

    // Section 5: Assessment
    if (yPos > 200) { doc.addPage(); yPos = 25; addPageDecoration(doc, doc.internal.getNumberOfPages()); }
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("5. ASSESSMENT WEIGHTAGE", 15, yPos);
    doc.autoTable({
      startY: yPos + 5,
      margin: { left: 15, right: 15 },
      head: [['Assessment Component', 'Weightage (%)']],
      body: [
        ['Quiz', `${course.assessment.quiz}%`],
        ['Test', `${course.assessment.test}%`],
        ['Assignment / PBL', `${course.assessment.assignment}%`],
        ['SEE (Semester End Exam)', `${course.assessment.see}%`],
        ['TOTAL', '100%']
      ],
      theme: 'grid',
      headStyles: { fillColor: [44, 62, 80] },
      styles: { fontSize: 9 }
    });
    yPos = doc.lastAutoTable.finalY + 15;

    // Section 6: Textbooks
    if (yPos > 240) { doc.addPage(); yPos = 25; addPageDecoration(doc, doc.internal.getNumberOfPages()); }
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("6. TEXTBOOKS & REFERENCES", 15, yPos);
    yPos += 7;
    doc.setFontSize(9);
    doc.setFont("helvetica", "normal");
    course.textbooks.forEach((book, idx) => {
      if (yPos > 270) { doc.addPage(); yPos = 25; addPageDecoration(doc, doc.internal.getNumberOfPages()); }
      doc.text(`${idx + 1}. ${book}`, 15, yPos);
      yPos += 6;
    });

    doc.save(`${course.courseCode}_Syllabus_Professional.pdf`);
  };

  if (loading) return <div className="loading">Loading course details...</div>;
  if (error) return <div className="error">{error}</div>;
  if (!course) return <div className="not-found">Course not found.</div>;

  return (
    <div className="course-detail-container">
      <Link to="/" className="back-link">
        <ArrowLeft size={16} /> Back to Search
      </Link>

      <div className="course-header-box">
        <div className="course-header-top">
          <div className="course-tags">
            <span className="tag code-tag">{course.courseCode}</span>
            <span className="tag ltp-tag"><Clock size={14} /> LTP: {course.ltp}</span>
            <span className="tag credit-tag"><Award size={14} /> {course.credits} Credits</span>
          </div>
          <button className="download-pdf-btn" onClick={generatePDF}>
            <Download size={18} /> Download PDF Syllabus
          </button>
        </div>
        <h1 className="course-detail-title">{course.courseTitle}</h1>
      </div>

      <div className="course-content-grid">
        <div className="main-column">
          <section className="detail-section card">
            <h2 className="section-title"><Book size={20} /> Course Aims and Summary</h2>
            <div className="section-content">
              <p className="full-text">{course.aims}</p>
            </div>
          </section>

          <section className="detail-section card">
            <h2 className="section-title"><Target size={20} /> Course Objectives</h2>
            <div className="section-content">
              <ul className="full-list">
                {course.objectives.map((obj, idx) => (
                  <li key={idx}>{obj}</li>
                ))}
              </ul>
            </div>
          </section>

          <section className="detail-section card">
            <h2 className="section-title"><CheckCircle size={20} /> Course Outcomes</h2>
            <div className="section-content">
              <table className="data-table">
                <thead>
                  <tr>
                    <th>CO Code</th>
                    <th>Course Outcome Description</th>
                  </tr>
                </thead>
                <tbody>
                  {course.outcomes.map((co, idx) => (
                    <tr key={idx}>
                      <td className="co-code">{co.code}</td>
                      <td>{co.description}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </section>

          <section className="detail-section card">
            <h2 className="section-title"><FileText size={20} /> Course Content (Syllabus)</h2>
            <div className="section-content">
              <div className="units-container">
                {course.syllabusUnits.map((unit, idx) => (
                  <div key={idx} className="unit-item">
                    <h3 className="unit-header">UNIT {unit.unitNumber}: {unit.title}</h3>
                    <div className="unit-topics">
                      {unit.topics.map((topic, i) => (
                        <span key={i} className="topic-tag">{topic}</span>
                      ))}
                    </div>
                  </div>
                ))}
              </div>
            </div>
          </section>
        </div>

        <div className="sidebar-column">
          <section className="detail-section sidebar-card">
            <h2 className="section-title"><BarChart size={20} /> Assessment</h2>
            <div className="section-content">
              <div className="assessment-grid">
                <div className="assessment-item">
                  <span className="label">Quiz</span>
                  <span className="value">{course.assessment.quiz}%</span>
                </div>
                <div className="assessment-item">
                  <span className="label">Test</span>
                  <span className="value">{course.assessment.test}%</span>
                </div>
                <div className="assessment-item">
                  <span className="label">Assignment</span>
                  <span className="value">{course.assessment.assignment}%</span>
                </div>
                <div className="assessment-item">
                  <span className="label">SEE</span>
                  <span className="value">{course.assessment.see}%</span>
                </div>
                <div className="assessment-total">
                  <span className="label">Total</span>
                  <span className="value">100%</span>
                </div>
              </div>
            </div>
          </section>

          <section className="detail-section sidebar-card">
            <h2 className="section-title"><BookOpen size={20} /> Textbooks</h2>
            <div className="section-content">
              <ul className="sidebar-list">
                {course.textbooks.map((book, idx) => (
                  <li key={idx}>{book}</li>
                ))}
              </ul>
            </div>
          </section>

          <section className="detail-section sidebar-card">
            <h2 className="section-title"><Layout size={20} /> Grading Scheme</h2>
            <div className="section-content">
              <table className="mini-table">
                <thead>
                  <tr>
                    <th>Range</th>
                    <th>Grade</th>
                  </tr>
                </thead>
                <tbody>
                  {course.grading.map((g, idx) => (
                    <tr key={idx}>
                      <td>{g.range}</td>
                      <td title={g.description}>{g.grade}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </section>
        </div>
      </div>
    </div>
  );
}

export default CourseDetail;
